/// User-facing texts in French, Dutch and English.
///
/// Kept as plain maps so the monitor, which has no widget tree, can use them
/// as well as the interface. Placeholders are written `{name}`.
library;

const supportedLanguages = ['fr', 'nl', 'en'];

class S {
  final String language;

  const S(this.language);

  /// Picks a supported language from a locale code, English by default.
  factory S.of(String? code) {
    final lang = (code ?? 'en').split(RegExp('[-_]')).first.toLowerCase();
    return S(supportedLanguages.contains(lang) ? lang : 'en');
  }

  String t(String key, [Map<String, String> args = const {}]) {
    var text = _texts[language]?[key] ?? _texts['en']![key] ?? key;
    args.forEach((k, v) => text = text.replaceAll('{$k}', v));
    return text;
  }

  /// "1 h 25 min", "25 min", "45 s".
  String duration(Duration d) {
    if (d.isNegative) d = Duration.zero;
    final h = d.inHours;
    final m = d.inMinutes % 60;
    if (h > 0) return m == 0 ? '$h h' : '$h h ${m.toString().padLeft(2, '0')}';
    if (d.inMinutes > 0) return '${d.inMinutes} min';
    if (d == Duration.zero) return '0 min';
    return '${d.inSeconds} s';
  }

  /// "20/10" (day/month), "20-10" in Dutch.
  String date(DateTime d) {
    final day = d.day.toString().padLeft(2, '0');
    final month = d.month.toString().padLeft(2, '0');
    return language == 'nl' ? '$day-$month' : '$day/$month';
  }

  /// "1 jour", "7 jours".
  String days(int n) =>
      n == 1 ? t('dayCount1') : t('daysCount', {'count': '$n'});

  /// "14:05".
  String time(DateTime t) =>
      '${t.hour.toString().padLeft(2, '0')}:${t.minute.toString().padLeft(2, '0')}';

  String weekday(int day) => t('weekday$day');

  /// An hour as said in a sentence: "9h", "9h30" in French; "9 uur",
  /// "9.30 uur" in Dutch; "9:00" in English.
  String hour(DateTime t) {
    final m = t.minute.toString().padLeft(2, '0');
    return switch (language) {
      'fr' => t.minute == 0 ? '${t.hour}h' : '${t.hour}h$m',
      'nl' => t.minute == 0 ? '${t.hour} uur' : '${t.hour}.$m uur',
      _ => '${t.hour}:$m',
    };
  }
}

